import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { parse } from 'csv-parse/sync';
import sharp from 'sharp';

const root = new URL('../', import.meta.url);
const cache = new URL('test-results/sky-sources/', root);
const output = new URL('public/solar-system/sky/', root);
const revision = 'c7f7f883fe678cc7680169a50ccd7dcc49b060ce';
const catalogueUrl = `https://raw.githubusercontent.com/astronexus/HYG-Database/${revision}/hyg/CURRENT/hygdata_v41.csv`;
const gaiaUrl = 'https://www.esa.int/var/esa/storage/images/esa_multimedia/images/2020/12/the_colour_of_the_sky_from_gaia_s_early_data_release_32/22358132-1-eng-GB/The_colour_of_the_sky_from_Gaia_s_Early_Data_Release_3.png';
await mkdir(cache, { recursive: true });
await mkdir(output, { recursive: true });
async function source(name, url) {
  const path = new URL(name, cache);
  try { return await readFile(path); } catch { /* Cache is optional. */ }
  const response = await fetch(url, { signal: AbortSignal.timeout(120000) });
  if (!response.ok) throw new Error(`Source download failed: ${response.status}`);
  const data = Buffer.from(await response.arrayBuffer());
  await writeFile(path, data);
  return data;
}
const catalogue = await source('hyg-v41.csv', catalogueUrl);
const rows = parse(catalogue, { columns: true, skip_empty_lines: true });
const stars = rows.filter(row => Number(row.id) !== 0 && row.mag !== '' && Number(row.mag) <= 6.5)
  .map(row => [Number(row.id), Number(row.rarad), Number(row.decrad), Number(row.mag), row.ci === '' ? null : Number(row.ci)])
  .sort((a, b) => a[3] - b[3] || a[0] - b[0]);
if (stars.length < 8000 || stars.length > 12000 || stars.some(row => !row.slice(0, 4).every(Number.isFinite))) {
  throw new Error('Unexpected catalogue contents');
}
const round = row => row.map((value, index) => index === 1 || index === 2 ? Number(value.toFixed(8)) : value);
const references = rows.filter(row => ['Sirius', 'Vega', 'Polaris', 'Betelgeuse'].includes(row.proper))
  .map(row => ({ name: row.proper, id: Number(row.id), hip: Number(row.hip), ra: Number(row.rarad), dec: Number(row.decrad), magnitude: Number(row.mag) }));
const manifest = {
  version: 1, catalogue: 'HYG v4.1', epoch: 'J2000.0', magnitudeLimit: 6.5,
  columns: ['hygId', 'raRadians', 'decRadians', 'visualMagnitude', 'bvColourIndex'],
  source: catalogueUrl, revision, sourceSha256: createHash('sha256').update(catalogue).digest('hex'),
  credit: 'David Nash / HYG; Hipparcos, Yale Bright Star and Gliese catalogues',
  license: 'CC BY-SA 4.0', licenseUrl: 'https://creativecommons.org/licenses/by-sa/4.0/',
  references, stars: stars.map(round),
};
await writeFile(new URL('hyg-v41-mag65.json', output), JSON.stringify(manifest));
await mkdir(new URL('solar-system/src/sky-data/', root), { recursive: true });
await writeFile(new URL('solar-system/src/sky-data/bright-stars.js', root),
  '// HYG v4.1 subset, David Nash. CC BY-SA 4.0. Generated by scripts/build-solar-sky.mjs.\n' +
  '// Full source, modifications and licence: /solar-system/sky/README.md\n' +
  `export const brightStars = ${JSON.stringify(stars.slice(0, 96).map(round))};\n`);

const gaia = await source('gaia-edr3.png', gaiaUrl);
// Suppress individual point sources before making a low-frequency background.
// The separate star catalogue supplies all resolvable star points.
const filtered = await sharp(gaia).resize(2048, 1024).median(5).toBuffer();
const diffuse = await sharp(filtered).resize(1024, 512).blur(2.5)
  .modulate({ saturation: 0.35 }).webp({ quality: 86 }).toBuffer();
await writeFile(new URL('gaia-edr3-diffuse.webp', output), diffuse);
await writeFile(new URL('gaia-edr3-source.json', output), JSON.stringify({
  source: gaiaUrl, sourceSha256: createHash('sha256').update(gaia).digest('hex'),
  page: 'https://www.esa.int/ESA_Multimedia/Images/2020/12/The_colour_of_the_sky_from_Gaia_s_Early_Data_Release_32',
  credit: 'ESA/Gaia/DPAC; acknowledgement: A. Moitinho.',
  license: 'CC BY-SA 3.0 IGO', licenseUrl: 'https://creativecommons.org/licenses/by-sa/3.0/igo/',
  projection: 'Galactic equirectangular; centre l=0,b=0; longitude increases to the left; north up',
  modifications: '2048x1024 median filter, 1024x512 resize, Gaussian blur, reduced saturation, WebP compression; display brightness further reduced in shader.',
}, null, 2));
console.log(JSON.stringify({ stars: stars.length, catalogueBytes: (await readFile(new URL('hyg-v41-mag65.json', output))).length, diffuseBytes: diffuse.length, references }));
